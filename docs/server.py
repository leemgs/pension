#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
노후 현금흐름(CIF) 시뮬레이터 로컬 서버
- 외부 패키지 설치 없이 Python 표준 라이브러리만으로 동작합니다.
- 종료 시 마지막 세팅(data/last_state.json)을 자동 저장하고 다음 실행 시 불러옵니다.
- 특정 조합 상태(Preset)를 data/presets/ 폴더에 저장/불러오기/삭제할 수 있습니다.
- 또한 data/embedded_state.js 에도 동기화하여, index.html 만 단독 실행해도 마지막 세팅과 프리셋이 그대로 재현됩니다.
"""

import http.server
import json
import os
import re
import socket
import sys
import threading
import time
import urllib.parse
import webbrowser
from datetime import datetime

if getattr(sys, "frozen", False):
    STATIC_DIR = getattr(sys, "_MEIPASS", os.path.dirname(os.path.abspath(__file__)))
    BASE_DIR = os.path.dirname(os.path.abspath(sys.executable))
else:
    STATIC_DIR = os.path.dirname(os.path.abspath(__file__))
    BASE_DIR = STATIC_DIR

DATA_DIR = os.path.join(BASE_DIR, "data")
PRESETS_DIR = os.path.join(DATA_DIR, "presets")
LAST_STATE_FILE = os.path.join(DATA_DIR, "last_state.json")
EMBEDDED_JS_FILE = os.path.join(DATA_DIR, "embedded_state.js")


def ensure_dirs():
    os.makedirs(DATA_DIR, exist_ok=True)
    os.makedirs(PRESETS_DIR, exist_ok=True)


def sanitize_filename(name: str) -> str:
    cleaned = re.sub(r'[\\/:*?"<>|]', "_", name.strip())
    return cleaned or "preset"


def load_last_state():
    if os.path.exists(LAST_STATE_FILE):
        try:
            with open(LAST_STATE_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception as e:
            print(f"[경고] last_state.json 읽기 실패: {e}")
    return None


def load_all_presets():
    presets = []
    if not os.path.exists(PRESETS_DIR):
        return presets
    for fname in sorted(os.listdir(PRESETS_DIR)):
        if fname.lower().endswith(".json"):
            fpath = os.path.join(PRESETS_DIR, fname)
            try:
                with open(fpath, "r", encoding="utf-8") as f:
                    data = json.load(f)
                    if isinstance(data, dict) and "name" in data and "state" in data:
                        presets.append(data)
            except Exception as e:
                print(f"[경고] 프리셋 파일 읽기 실패 ({fname}): {e}")
    presets.sort(key=lambda x: x.get("updatedAt", ""), reverse=True)
    return presets


def sync_embedded_js():
    """
    단독 HTML 실행(index.html 더블클릭)이나 다른 PC로 폴더 이동 시에도
    별도 서버 없이 마지막 세팅과 프리셋을 즉시 읽을 수 있도록 JS 번들 형태로 동기화합니다.
    """
    ensure_dirs()
    last_state = load_last_state()
    presets = load_all_presets()
    payload = {
        "lastState": last_state,
        "presets": presets,
        "syncedAt": datetime.now().isoformat(timespec="seconds"),
    }
    js_content = (
        "// Auto-generated by server.py - Do not edit manually\n"
        "window.__PORTABLE_STORAGE__ = "
        + json.dumps(payload, ensure_ascii=False, indent=2)
        + ";\n"
    )
    try:
        with open(EMBEDDED_JS_FILE, "w", encoding="utf-8") as f:
            f.write(js_content)
    except Exception as e:
        print(f"[경고] embedded_state.js 동기화 실패: {e}")


def save_last_state(state_obj):
    ensure_dirs()
    wrapper = {
        "updatedAt": datetime.now().isoformat(timespec="seconds"),
        "state": state_obj,
    }
    with open(LAST_STATE_FILE, "w", encoding="utf-8") as f:
        json.dump(wrapper, f, ensure_ascii=False, indent=2)
    sync_embedded_js()
    return wrapper


def save_preset(name: str, description: str, state_obj: dict):
    ensure_dirs()
    safe_name = sanitize_filename(name)
    fpath = os.path.join(PRESETS_DIR, f"{safe_name}.json")
    preset_obj = {
        "name": name.strip(),
        "description": (description or "").strip(),
        "updatedAt": datetime.now().isoformat(timespec="seconds"),
        "state": state_obj,
    }
    with open(fpath, "w", encoding="utf-8") as f:
        json.dump(preset_obj, f, ensure_ascii=False, indent=2)
    sync_embedded_js()
    return preset_obj


def delete_preset(name: str) -> bool:
    ensure_dirs()
    safe_name = sanitize_filename(name)
    fpath = os.path.join(PRESETS_DIR, f"{safe_name}.json")
    removed = False
    if os.path.exists(fpath):
        os.remove(fpath)
        removed = True
    else:
        # 파일명과 내부 name이 다를 경우 탐색
        for fname in os.listdir(PRESETS_DIR):
            if fname.lower().endswith(".json"):
                p = os.path.join(PRESETS_DIR, fname)
                try:
                    with open(p, "r", encoding="utf-8") as f:
                        d = json.load(f)
                    if d.get("name") == name:
                        os.remove(p)
                        removed = True
                        break
                except Exception:
                    pass
    sync_embedded_js()
    return removed


class SimulatorRequestHandler(http.server.SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=STATIC_DIR, **kwargs)

    def log_message(self, format, *args):
        # 정적 파일 로그는 간소화
        msg = format % args
        if "/api/" in msg or "GET / " in msg:
            print(f"[{datetime.now().strftime('%H:%M:%S')}] {msg}")

    def _send_json(self, data, status=200):
        body = json.dumps(data, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store, no-cache, must-revalidate")
        self.end_headers()
        self.wfile.write(body)

    def _read_json_body(self):
        length = int(self.headers.get("Content-Length", 0))
        if length <= 0:
            return {}
        raw = self.rfile.read(length).decode("utf-8")
        return json.loads(raw)

    def do_GET(self):
        parsed = urllib.parse.urlparse(self.path)
        if parsed.path == "/api/bootstrap":
            last_state = load_last_state()
            presets = load_all_presets()
            self._send_json(
                {
                    "ok": True,
                    "serverMode": True,
                    "lastState": last_state,
                    "presets": presets,
                }
            )
            return
        elif parsed.path == "/api/presets":
            self._send_json({"ok": True, "presets": load_all_presets()})
            return

        return super().do_GET()

    def do_POST(self):
        parsed = urllib.parse.urlparse(self.path)
        try:
            body = self._read_json_body()
        except Exception as e:
            self._send_json({"ok": False, "error": str(e)}, status=400)
            return

        if parsed.path == "/api/state":
            state_obj = body.get("state", body)
            saved = save_last_state(state_obj)
            self._send_json({"ok": True, "updatedAt": saved["updatedAt"]})
            return

        elif parsed.path == "/api/presets":
            name = (body.get("name") or "").strip()
            description = body.get("description") or ""
            state_obj = body.get("state")
            if not name or not isinstance(state_obj, dict):
                self._send_json(
                    {"ok": False, "error": "프리셋 이름과 상태 데이터가 필요합니다."},
                    status=400,
                )
                return
            preset = save_preset(name, description, state_obj)
            self._send_json(
                {"ok": True, "preset": preset, "presets": load_all_presets()}
            )
            return

        elif parsed.path == "/api/presets/import":
            # 외부 JSON 파일에서 프리셋 일괄 가져오기
            imported_presets = body.get("presets", [])
            last_state = body.get("lastState")
            if isinstance(last_state, dict):
                save_last_state(last_state.get("state", last_state))
            if isinstance(imported_presets, list):
                for p in imported_presets:
                    if isinstance(p, dict) and p.get("name") and p.get("state"):
                        save_preset(
                            p["name"], p.get("description", ""), p["state"]
                        )
            self._send_json(
                {
                    "ok": True,
                    "lastState": load_last_state(),
                    "presets": load_all_presets(),
                }
            )
            return

        self._send_json({"ok": False, "error": "Not found"}, status=404)

    def do_DELETE(self):
        parsed = urllib.parse.urlparse(self.path)
        if parsed.path == "/api/presets":
            qs = urllib.parse.parse_qs(parsed.query)
            name = (qs.get("name", [""])[0]).strip()
            if not name:
                self._send_json(
                    {"ok": False, "error": "삭제할 프리셋 이름이 없습니다."},
                    status=400,
                )
                return
            removed = delete_preset(name)
            self._send_json(
                {
                    "ok": True,
                    "removed": removed,
                    "presets": load_all_presets(),
                }
            )
            return
        self._send_json({"ok": False, "error": "Not found"}, status=404)


def find_free_port(preferred=8765):
    for port in range(preferred, preferred + 50):
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            try:
                s.bind(("127.0.0.1", port))
                return port
            except OSError:
                continue
    return 0


def main():
    ensure_dirs()
    if not os.path.exists(EMBEDDED_JS_FILE):
        sync_embedded_js()

    port = find_free_port(8765)
    server = http.server.ThreadingHTTPServer(
        ("127.0.0.1", port), SimulatorRequestHandler
    )
    url = f"http://127.0.0.1:{port}"

    print("=" * 68)
    print("  노후 현금흐름(CIF) & 세금·건보료 정밀 시뮬레이터")
    print("=" * 68)
    print(f"  - 접속 주소     : {url}")
    print(f"  - 자동 저장 경로: {LAST_STATE_FILE}")
    print(f"  - 프리셋 폴더   : {PRESETS_DIR}")
    print("  - 다른 PC로 폴더 전체를 복사하면 마지막 세팅과 프리셋이 100% 재현됩니다.")
    print("  - 종료하려면 이 창을 닫거나 Ctrl+C 를 누르세요.")
    print("=" * 68)

    if "--no-browser" not in sys.argv:
        threading.Timer(0.6, lambda: webbrowser.open(url)).start()

    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\n[알림] 서버가 안전하게 종료되었습니다. 마지막 설정이 저장되었습니다.")
        server.server_close()


if __name__ == "__main__":
    main()

